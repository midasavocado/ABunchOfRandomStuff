_VCACHE = {}


def mesh_points(o, stride=7):
    key = (o.data.name, stride)
    if key not in _VCACHE:
        n = len(o.data.vertices)
        a = np.empty(n * 3, np.float32)
        o.data.vertices.foreach_get("co", a)
        _VCACHE[key] = a.reshape(-1, 3)[::stride].astype(np.float64)
    return _VCACHE[key]


def world_pts(o, stride=7):
    bpy.context.view_layer.update()
    P = mesh_points(o, stride)
    M = np.array(o.matrix_world)
    return P @ M[:3, :3].T + M[:3, 3]


def cyl_clearance(P, c, axis, r):
    """min(distance to the cylinder axis) - r (negative = penetration)."""
    c = np.asarray(c); a = np.asarray(axis) / np.linalg.norm(axis)
    q = P - c
    along = q @ a
    perp = q - along[:, None] * a[None, :]
    return float(np.min(np.linalg.norm(perp, axis=1)) - r)


def solve_curl(finger, clearance_fn, th1_range=(0.0, 1.6), th2_ratio=1.0, gap=0.0002, th2_extra=(0.0, 1.5)):
    """Adaptive grasp: close the proximal link until it (or the distal driven at th2_ratio) touches, then keep
    closing the distal alone until its pad touches. clearance_fn(points)->float. Returns (th1, th2)."""
    def clr(th1, th2):
        finger.set(th1, th2)
        return min(clearance_fn(world_pts(finger.link)), clearance_fn(world_pts(finger.dmesh)))
    lo, hi = th1_range
    if clr(hi, hi * th2_ratio) > gap:
        th1 = hi
    else:
        for _ in range(26):
            mid = 0.5 * (lo + hi)
            if clr(mid, mid * th2_ratio) > gap: lo = mid
            else: hi = mid
        th1 = lo
    base2 = th1 * th2_ratio
    lo, hi = base2, base2 + th2_extra[1]
    def clr2(th2):
        finger.set(th1, th2)
        return clearance_fn(world_pts(finger.dmesh))
    if clr2(hi) > gap:
        th2 = hi
    else:
        for _ in range(26):
            mid = 0.5 * (lo + hi)
            if clr2(mid) > gap: lo = mid
            else: hi = mid
        th2 = lo
    finger.set(th1, th2)
    return th1, th2
