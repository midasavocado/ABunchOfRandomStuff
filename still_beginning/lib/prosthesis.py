def silicone():
    if "sil" not in _MATS:
        m = sb.mat("ProSilicone", (0.045, 0.046, 0.05), rough=0.62, spec=0.35)
        nb = sb.NB(m)
        co = nb.coord('Object')
        # fine grip texture: tiny dimples
        vv = nb.voronoi(co, scale=1400, feature='F1')
        nb.set('Normal', nb.bump(nb.maprange(vv.outputs['Distance'], 0.0, 0.4, 0.0, 1.0), strength=0.1, distance=0.00004))
