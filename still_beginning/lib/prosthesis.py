def steel_pin():
    if "pin" not in _MATS:
        _MATS["pin"] = sb.brushed_metal("ProPin", (0.78, 0.78, 0.79), rough=0.18, aniso=0.3, scale=200, bump=0.01)
    return _MATS["pin"]


def carbon():
    """Forearm socket: carbon composite under a clear coat - low-contrast 3 mm tow checker, satin coat."""
    if "carbon" not in _MATS:
        m = sb.mat("ProCarbon", (0.03, 0.031, 0.035), rough=0.32, coat=0.9, coat_rough=0.06, spec=0.5)
        nb = sb.NB(m)
        co = nb.coord('Object')
        ch = nb.new('ShaderNodeTexChecker')
        nb.link(nb.mapping(co, rot=(0.0, 0.0, 0.785)), ch.inputs['Vector'])
        ch.inputs['Scale'].default_value = 420.0
        f = ch.outputs['Fac']
        nb.set('Base Color', nb.mix(f, (0.026, 0.027, 0.030, 1), (0.036, 0.037, 0.041, 1)))
        nb.set('Roughness', nb.mix(f, 0.26, 0.42, dtype='FLOAT'))
        nb.b = None
        _MATS["carbon"] = m
    return _MATS["carbon"]


# ------------------------------------------------------------------ mesh loading

_MESH_CACHE = {}


def load_npz(path, name, mat=None, smooth=True):
    """Load V/F npz as a mesh object (mesh datablock cached so instances share data)."""
    if path in _MESH_CACHE:
        me = _MESH_CACHE[path]
    else:
        D = np.load(path)
        Vv, F = D["V"], D["F"]
        me = bpy.data.meshes.new(os.path.basename(path))
        me.vertices.add(len(Vv))
        me.vertices.foreach_set("co", Vv.ravel())
        me.loops.add(len(F) * 3)
        me.loops.foreach_set("vertex_index", F.ravel())
        me.polygons.add(len(F))
        me.polygons.foreach_set("loop_start", np.arange(0, len(F) * 3, 3))
        me.polygons.foreach_set("loop_total", np.full(len(F), 3))
        me.update(calc_edges=True)
        me.validate()
        me.polygons.foreach_set("use_smooth", np.ones(len(F), bool))
        if "A" in D.files:
            A = D["A"]
            at = me.color_attributes.new("mask", 'FLOAT_COLOR', 'POINT')
            at.data.foreach_set("color", np.concatenate([A, np.ones((len(A), 1), np.float32)], 1).ravel())
        if mat:
            me.materials.append(mat)
        _MESH_CACHE[path] = me
    o = bpy.data.objects.new(name, me)
    sb.link_obj(o)
    return o


def part_path(ver="v3"):
    return os.path.join(ROOT, "assets", "part", ver + ".npz")


def bushing(name, r_in, r_out, hw, flange=0.0009, mat=None):
    """Amber anodized flanged bushing along X, flush with the machined faces at |x| = hw; the 45deg chamfer on
    the flange is the machined amber edge that catches the light."""
    ch = 0.00028
    prof = [(r_in, -hw - 0.00012), (r_out + flange - ch, -hw - 0.00012), (r_out + flange, -hw - 0.00012 + ch),
            (r_out + flange, -hw + 0.00035), (r_out, -hw + 0.00035), (r_out, hw - 0.00035), (r_out + flange, hw - 0.00035),
            (r_out + flange, hw + 0.00012 - ch), (r_out + flange - ch, hw + 0.00012), (r_in, hw + 0.00012), (r_in, -hw - 0.00012)]
    o = sb.lathe(name, [(r, z) for r, z in prof], segs=96, mat=mat or amber(), axis='X')
    return o


def component(ver="v3", name="Link", parent=None, bushings=True, mat=None):
    """The component in part frame under an empty. Returns (root_empty, mesh_obj)."""
    root = sb.empty(name, parent=parent)
    o = load_npz(part_path(ver), name + "Mesh", mat or ti_sintered())
    o.parent = root
    if bushings and ver == "v3":
        b1 = bushing(name + "BushMCP", BORE_MCP - 0.0006, BORE_MCP, W_MCP)
        b1.parent = root
        b2 = bushing(name + "BushPIP", BORE_PIP - 0.0005, BORE_PIP, 0.00255, flange=0.0007)
        b2.location = (0, PART_L, 0)
        b2.parent = root
        # the PIP bushing sits in the outer clevis ears: two short ones
        b2.scale = (1, 1, 1)
        for s in (-1, 1):
            e = bushing(name + "BushPIPe", BORE_PIP - 0.0005, BORE_PIP, 0.0017, flange=0.0006)
            e.location = (s * (W_PIP - 0.0017), PART_L, 0)
            e.parent = root
        bpy.data.objects.remove(b2)
    return root, o


