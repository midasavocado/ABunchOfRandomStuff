"""THE prosthetic design for the making sequence (s06 design, s07 fabrication/robot, s08 finger, s09 table).
ONE design: the proximal-phalanx link generated by lib/sdfpart.py ('v3' = final), fitted in a 2-segment
finger (proximal link + distal shell with silicone pad, four-bar coupler), five fingers on a white palm
chassis with a graphite frame, amber anodized bushings + amber wrist ring (the curved amber highlight).
All units metres. Part frame: MCP axis = X through origin, PIP axis = X through (0, PART_L, 0), dorsal +Z."""
import bpy, math, os
import numpy as np
from mathutils import Vector as V, Matrix, Quaternion, Euler
import sb, props

ROOT = sb.ROOT
PART_L = 0.040
BORE_MCP, BORE_PIP = 0.00205, 0.00155
W_MCP, W_PIP = 0.007, 0.006
_MATS = {}


# ------------------------------------------------------------------ materials

def ti_sintered(name="TiSLM", build=False):
    """Laser-sintered + bead-blasted titanium: warm grey, satin, fine granular micro-relief. Machined flats
    (|n.x| ~ 1 in object space) are brighter, smoother, with concentric turning marks around the pivot."""
    key = (name, build)
    if key in _MATS:
        return _MATS[key]
    col = (0.50, 0.48, 0.455) if not build else (0.42, 0.41, 0.40)
    m = sb.mat(name, col, metal=1.0, rough=0.42)
    nb = sb.NB(m)
    co = nb.coord('Object')
    nrm = nb.coord('Normal')
    sepn = nb.new('ShaderNodeSeparateXYZ'); nb.link(nrm, sepn.inputs[0])
    flat = nb.maprange(nb.math('ABSOLUTE', sepn.outputs[0]), 0.965, 0.995)
    if build:
        flat = nb.math('MULTIPLY', flat, 0.0)
    # granular SLM texture (partially fused powder ~ 30-50 um)
    g1 = nb.voronoi(co, scale=26000, feature='F1')
    g2 = nb.noise(co, scale=5200, detail=4, rough=0.6)
    grain = nb.math('ADD', nb.math('MULTIPLY', nb.maprange(g1.outputs['Distance'], 0.0, 0.5, 1.0, 0.0), 0.6),
                    nb.math('MULTIPLY', g2.outputs['Fac'], 0.5))
    # faint build-layer lines (40 um along Z of the build = part local X/Y mix) only on sintered faces
    sep = nb.new('ShaderNodeSeparateXYZ'); nb.link(co, sep.inputs[0])
    layers = nb.math('SINE', nb.math('MULTIPLY', sep.outputs[2], 2 * math.pi / 0.00005))
    grain = nb.math('ADD', grain, nb.math('MULTIPLY', layers, 0.12))
    # concentric turning marks around the MCP or PIP axis (choose by y)
    y = sep.outputs[1]; z = sep.outputs[2]
    near_pip = nb.maprange(y, PART_L * 0.45, PART_L * 0.55)
    yc = nb.math('SUBTRACT', y, nb.math('MULTIPLY', near_pip, PART_L))
    rad = nb.math('SQRT', nb.math('ADD', nb.math('MULTIPLY', yc, yc), nb.math('MULTIPLY', z, z)))
    turn = nb.math('SINE', nb.math('MULTIPLY', rad, 2 * math.pi / 0.000045))
    h = nb.mix(flat, grain, nb.math('MULTIPLY', turn, 0.15), dtype='FLOAT')
    nb.set('Normal', nb.bump(h, strength=0.35, distance=0.00003))
    # colour: slight mottling (heat tint / oxide) on sintered faces, bright on machined flats
    mott = nb.noise(co, scale=260, detail=3)
    c_s = nb.mix(nb.maprange(mott.outputs['Fac'], 0.3, 0.7), (col[0] * 0.9, col[1] * 0.9, col[2] * 0.9, 1),
                 (col[0] * 1.05, col[1] * 1.03, col[2] * 1.0, 1))
    nb.set('Base Color', nb.mix(flat, c_s, (0.70, 0.69, 0.67, 1)))
    r_s = nb.maprange(g2.outputs['Fac'], 0.3, 0.7, 0.36, 0.48)
    nb.set('Roughness', nb.mix(flat, r_s, 0.17, dtype='FLOAT'))
    b = nb.bsdf
    b.inputs['Anisotropic'].default_value = 0.0
    _MATS[key] = m
    return m


def amber():
    if "amber" not in _MATS:
        m = props.amber_anodized("ProAmber")
        # anodized aluminium: add a clear-ish coat for the gem-like edge highlight
        b = m.node_tree.nodes["Principled BSDF"]
        b.inputs['Coat Weight'].default_value = 0.25
        b.inputs['Coat Roughness'].default_value = 0.12
        _MATS["amber"] = m
    return _MATS["amber"]


def shell_white():
    """Soft-touch cover polymer: warm white, matte-satin, micro orange-peel, faint SSS."""
    if "white" not in _MATS:
        m = sb.mat("ProWhite", (0.80, 0.79, 0.765), rough=0.46, spec=0.45, sss=0.08, sss_radius=(1, 0.9, 0.8),
                   sss_scale=0.002, coat=0.15, coat_rough=0.3)
        nb = sb.NB(m)
        co = nb.coord('Object')
        n = nb.noise(co, scale=2600, detail=3, rough=0.6)
        nb.set('Normal', nb.bump(n.outputs['Fac'], strength=0.08, distance=0.0001))
        nb.set('Roughness', nb.maprange(n.outputs['Fac'], 0.3, 0.7, 0.42, 0.5))
        _MATS["white"] = m
    return _MATS["white"]


def graphite():
    if "graph" not in _MATS:
        m = sb.mat("ProGraphite", (0.035, 0.036, 0.04), metal=0.0, rough=0.38, spec=0.5, coat=0.2, coat_rough=0.25)
        nb = sb.NB(m)
        co = nb.coord('Object')
        n = nb.noise(co, scale=3000, detail=3)
        nb.set('Normal', nb.bump(n.outputs['Fac'], strength=0.1, distance=0.0001))
