def distal_mat():
    """White shell + dark silicone pad below the groove (object z < -1.2 mm, y > 11 mm) + graphite tongue."""
    if "distal" in _MATS:
        return _MATS["distal"]
    m = bpy.data.materials.new("ProDistal")
    m.use_nodes = True
    nt = m.node_tree
    nt.nodes.clear()
    out = nt.nodes.new('ShaderNodeOutputMaterial')
    nb = sb.NB.__new__(sb.NB)
    nb.m, nb.nt, nb.n, nb.l = m, nt, nt.nodes, nt.links
    at = nb.new('ShaderNodeAttribute'); at.attribute_name = "mask"
    sep = nb.new('ShaderNodeSeparateColor'); nb.link(at.outputs['Color'], sep.inputs[0])
    pad, tongue = nb.maprange(sep.outputs[0], 0.35, 0.65), nb.maprange(sep.outputs[1], 0.35, 0.65)
    sh_w = _shader_of(nt, shell_white())
    sh_s = _shader_of(nt, silicone())
    sh_g = _shader_of(nt, graphite())
    mx = nt.nodes.new('ShaderNodeMixShader'); nb.link(pad, mx.inputs[0]); nb.link(sh_w, mx.inputs[1]); nb.link(sh_s, mx.inputs[2])
    mx2 = nt.nodes.new('ShaderNodeMixShader'); nb.link(tongue, mx2.inputs[0]); nb.link(mx.outputs[0], mx2.inputs[1]); nb.link(sh_g, mx2.inputs[2])
    nb.link(mx2.outputs[0], out.inputs[0])
    _MATS["distal"] = m
    return m


def _shader_of(nt_dst, src_mat):
    """Copy a Principled-based material's node tree into nt_dst as a node group; return its shader output."""
    gname = "G_" + src_mat.name
    g = bpy.data.node_groups.get(gname)
    if g is None:
        g = bpy.data.node_groups.new(gname, 'ShaderNodeTree')
        g.interface.new_socket("Shader", in_out='OUTPUT', socket_type='NodeSocketShader')
        go = g.nodes.new('NodeGroupOutput')
        mp = {}
        for n in src_mat.node_tree.nodes:
            if n.bl_idname == 'ShaderNodeOutputMaterial':
                continue
            nn = g.nodes.new(n.bl_idname)
            for attr in ('operation', 'blend_type', 'data_type', 'noise_dimensions', 'voronoi_dimensions', 'feature',
                         'distance', 'wave_type', 'bands_direction', 'rings_direction', 'wave_profile', 'use_clamp',
                         'clamp', 'clamp_factor', 'clamp_result', 'subsurface_method', 'distribution', 'noise_type',
                         'vector_type', 'interpolation_type', 'attribute_name', 'attribute_type'):
                if hasattr(n, attr):
                    try: setattr(nn, attr, getattr(n, attr))
                    except Exception: pass
            if n.bl_idname == 'ShaderNodeValToRGB':
                cr, cr2 = n.color_ramp, nn.color_ramp
                while len(cr2.elements) < len(cr.elements):
                    cr2.elements.new(0.5)
                for e, e2 in zip(cr.elements, cr2.elements):
                    e2.position = e.position; e2.color = e.color
            for i, s in enumerate(n.inputs):
                if hasattr(s, 'default_value'):
                    try: nn.inputs[i].default_value = s.default_value
                    except Exception: pass
            mp[n.name] = nn
        for l in src_mat.node_tree.links:
            if l.to_node.bl_idname == 'ShaderNodeOutputMaterial':
                fi = list(l.from_node.outputs).index(l.from_socket)
                g.links.new(mp[l.from_node.name].outputs[fi], go.inputs[0])
                continue
            fi = list(l.from_node.outputs).index(l.from_socket)
            ti = list(l.to_node.inputs).index(l.to_socket)
            g.links.new(mp[l.from_node.name].outputs[fi], mp[l.to_node.name].inputs[ti])
    gn = nt_dst.nodes.new('ShaderNodeGroup')
    gn.node_tree = g
    return gn.outputs[0]


def palm_mat():
    """Palm: white dorsal cover (z > 3 mm and behind the yokes) over a graphite frame; dark silicone palmar pad."""
    if "palm" in _MATS:
        return _MATS["palm"]
    m = bpy.data.materials.new("ProPalm")
    m.use_nodes = True
    nt = m.node_tree
    nt.nodes.clear()
    out = nt.nodes.new('ShaderNodeOutputMaterial')
    nb = sb.NB.__new__(sb.NB)
    nb.m, nb.nt, nb.n, nb.l = m, nt, nt.nodes, nt.links
    at = nb.new('ShaderNodeAttribute'); at.attribute_name = "mask"
    sep = nb.new('ShaderNodeSeparateColor'); nb.link(at.outputs['Color'], sep.inputs[0])
    cover, palmar = nb.maprange(sep.outputs[0], 0.35, 0.65), nb.maprange(sep.outputs[1], 0.35, 0.65)
    sh_w = _shader_of(nt, shell_white()); sh_g = _shader_of(nt, graphite()); sh_s = _shader_of(nt, silicone())
    mx = nt.nodes.new('ShaderNodeMixShader'); nb.link(cover, mx.inputs[0]); nb.link(sh_g, mx.inputs[1]); nb.link(sh_w, mx.inputs[2])
    mx2 = nt.nodes.new('ShaderNodeMixShader'); nb.link(palmar, mx2.inputs[0]); nb.link(mx.outputs[0], mx2.inputs[1]); nb.link(sh_s, mx2.inputs[2])
    nb.link(mx2.outputs[0], out.inputs[0])
    _MATS["palm"] = m
    return m


# ------------------------------------------------------------------ finger

FINGER_MCP = {"index": ((-24.0, 80.0, 2.0), -5.0), "middle": ((-4.2, 83.0, 2.5), -1.0),
              "ring": ((15.2, 80.5, 2.0), 3.5), "pinky": ((32.5, 72.0, 0.5), 9.0)}   # keep in sync with sdfpart
FINGER_SCALE = {"index": 0.96, "middle": 1.0, "ring": 0.96, "pinky": 0.8, "thumb": 0.86}


class Finger:
    """base (fixed, MCP frame) -> prox (rot X = -th1) -> [component] -> dist at PIP (rot X = -th2) -> [distal]."""

    def __init__(self, name, parent=None, scale=1.0, tendon=True, pins=True, part_ver="v3"):
        self.name = name
        self.s = scale
        self.base = sb.empty(name + "Base", parent=parent)
        self.prox = sb.empty(name + "Prox", parent=self.base)
        self.prox.rotation_mode = 'XYZ'
        self.link_root, self.link = component(part_ver, name + "Link", parent=self.prox)
        self.link_root.scale = (1, scale, scale) if scale != 1.0 else (1, 1, 1)
        self.dist = sb.empty(name + "Dist", loc=(0, PART_L * scale, 0), parent=self.prox)
        self.dist.rotation_mode = 'XYZ'
        self.dmesh = load_npz(os.path.join(ROOT, "assets", "part", "distal.npz"), name + "Distal", distal_mat())
        self.dmesh.parent = self.dist
        self.dmesh.scale = (scale * 1.1, scale, scale)
        self.objs = [self.link, self.dmesh]
        if pins:
            pm = steel_pin()
            p1 = sb.prim("cyl", name + "PinMCP", rot=(0, math.pi / 2, 0), vertices=32, radius=BORE_MCP - 0.00062,
                         depth=0.0196, mat=pm, parent=self.base)
            p2 = sb.prim("cyl", name + "PinPIP", rot=(0, math.pi / 2, 0), vertices=32, radius=BORE_PIP - 0.00052,
                         depth=0.0128, mat=pm, parent=self.dist)
            for p in (p1, p2):
                sb.bevel(p, 0.00015, 2)
            self.pins = (p1, p2)
        self.tendon = None
        if tendon:
            self._tendon()

    def _tendon(self):
        s = self.s
        pts_local = [(self.base, (0, -0.030, -0.0045)), (self.base, (0, -0.004, -0.0072)), (self.base, (0, 0.0, -0.0074)),
                     (self.prox, (0, 0.0084 * s, -0.005 * s)), (self.prox, (0, 0.030 * s, -0.0052 * s)),
                     (self.prox, (0, 0.0385 * s, -0.0056 * s)), (self.dist, (0, 0.003 * s, -0.0056 * s)),
                     (self.dist, (0, 0.0076 * s, -0.0049 * s))]
        bpy.context.view_layer.update()
        world = [o.matrix_world @ V(p) for o, p in pts_local]
        cu = bpy.data.curves.new(self.name + "Tendon", 'CURVE')
        cu.dimensions = '3D'
        cu.bevel_depth = 0.00042 * s
        cu.bevel_resolution = 3
        sp = cu.splines.new('POLY')
        sp.points.add(len(world) - 1)
        for i, p in enumerate(world):
            sp.points[i].co = (*p, 1)
        o = bpy.data.objects.new(self.name + "Tendon", cu)
        sb.link_obj(o)
        o.data.materials.append(tendon_mat())
        for i, (own, p) in enumerate(pts_local):
            h = sb.empty(self.name + "TH%d" % i, loc=p, parent=own)
            mod = o.modifiers.new("H%d" % i, 'HOOK')
            mod.object = h
            mod.vertex_indices_set([i])
            mod.center = world[i]
        self.tendon = o

    def set(self, th1, th2, frame=None):
        self.prox.rotation_euler = (-th1, 0, 0)
        self.dist.rotation_euler = (-th2, 0, 0)
        if frame is not None:
            self.prox.keyframe_insert("rotation_euler", frame=frame, index=0)
            self.dist.keyframe_insert("rotation_euler", frame=frame, index=0)


def tendon_mat():
    if "tendon" not in _MATS:
        m = sb.mat("ProTendon", (0.82, 0.80, 0.74), rough=0.55, sheen=0.4)
        nb = sb.NB(m)
        co = nb.coord('Object')
        w = nb.wave(co, scale=4000, wtype='BANDS', direction='Y', dist=2)
        nb.set('Normal', nb.bump(w.outputs['Fac'], strength=0.3, distance=0.00005))
        _MATS["tendon"] = m
    return _MATS["tendon"]


# ------------------------------------------------------------------ hand

class Hand:
    """Complete right prosthetic hand. root = wrist centre (fingers +Y, dorsal +Z, thumb -X)."""

    def __init__(self, name="PHand", parent=None, socket=True, tendons=False):
        self.root = sb.empty(name, parent=parent)
        self.palm = load_npz(os.path.join(ROOT, "assets", "part", "palm.npz"), name + "Palm", palm_mat())
        self.palm.parent = self.root
        self.fingers = {}
        for fn, ((mx, my, mz), sp) in FINGER_MCP.items():
            f = Finger(name + fn, parent=self.root, scale=FINGER_SCALE[fn], tendon=tendons)
            f.base.location = (mx * 0.001, my * 0.001, mz * 0.001)
            f.base.rotation_euler = (0, 0, -math.radians(sp))
            self.fingers[fn] = f
        # thumb: rotator on the thenar housing
        self.thumb_rot = sb.empty(name + "ThumbRot", loc=(-0.030, 0.027, -0.009), parent=self.root)
        self.thumb_rot.rotation_mode = 'QUATERNION'
        t = Finger(name + "thumb", parent=self.thumb_rot, scale=FINGER_SCALE["thumb"], tendon=tendons)
        self.fingers["thumb"] = t
        hub = sb.prim("cyl", name + "ThumbHub", loc=(0, 0, 0), rot=(0, math.pi / 2, 0), vertices=48, radius=0.0068,
                      depth=0.0185, mat=graphite(), parent=t.base)
        sb.bevel(hub, 0.0012, 3)
        # wrist quick-disconnect: amber anodized ring (the curved amber highlight) + graphite collar
        ring = sb.lathe(name + "WristRing", [(0.0208, -0.0125), (0.0218, -0.0120), (0.0222, -0.0108), (0.0222, -0.0072),
                                              (0.0218, -0.0062), (0.0208, -0.0057)], segs=160, mat=amber(), axis='Y')
        ring.rotation_euler = (-math.pi / 2, 0, 0)
        ring.scale = (1.25, 1.0, 1)
        ring.location = (0, 0, -0.001)
        ring.parent = self.root
        self.ring = ring
        self.socket = None
        if socket:
            prof = [(0.0212, -0.0128), (0.0218, -0.022), (0.0236, -0.07), (0.0262, -0.13), (0.0290, -0.19),
                    (0.0312, -0.235), (0.0322, -0.245), (0.0300, -0.247), (0.0282, -0.24)]
            so = sb.lathe(name + "Socket", prof, segs=128, mat=carbon(), axis='Y')
            so.rotation_euler = (-math.pi / 2, 0, 0)
            so.scale = (1.22, 1.0, 1.0)
            so.location = (0, 0, -0.001)
            so.parent = self.root
            sb.solidify(so, 0.0025, offset=1)
            self.socket = so

    def set_thumb_frame(self, d, z):
        """d: thumb direction (hand frame), z: thumb dorsal direction (hand frame)."""
        d = V(d).normalized(); z = (V(z) - V(d) * V(z).dot(V(d))).normalized()
        x = d.cross(z)
        self.thumb_rot.rotation_quaternion = Matrix((x, d, z)).transposed().to_quaternion()


